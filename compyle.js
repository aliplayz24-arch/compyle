#!/usr/bin/env bun

import { spawnSync } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";
import * as os from "node:os";

// -------------------------------------------------------------
// 1. PYTHON METADATA & IMPORT ANALYZER (FROM SCRATCH)
// -------------------------------------------------------------

function extractImports(source) {
  const imports = [];
  const lines = source.split(/\r?\n/);

  for (let rawLine of lines) {
    // Strip comments
    const commentIdx = rawLine.indexOf("#");
    const line = (commentIdx !== -1 ? rawLine.slice(0, commentIdx) : rawLine).trim();
    if (!line) continue;

    const tokens = line.split(/\s+/);

    if (tokens[0] === "import") {
      // Handles: import os, sys as system, math
      for (let i = 1; i < tokens.length; i++) {
        const token = tokens[i].replace(/,$/, "");
        if (token === "as") {
          i++; // Skip the alias
          continue;
        }
        if (token) imports.push({ type: "ModImport", module: token });
      }
    } else if (tokens[0] === "from" && tokens.length >= 4) {
      // Handles: from math import sin, cos as c
      const modName = tokens[1];
      const importIdx = tokens.indexOf("import");
      if (importIdx !== -1) {
        for (let i = importIdx + 1; i < tokens.length; i++) {
          const target = tokens[i].replace(/,$/, "");
          if (target === "as") {
            i++;
            continue;
          }
          if (target) imports.push({ type: "FromImport", module: modName, target });
        }
      }
    }
  }

  // Deduplicate
  const seen = new Set();
  return imports.filter((item) => {
    const key = `${item.type}:${item.module}:${item.target || ""}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

// -------------------------------------------------------------
// 2. CROSS-PLATFORM PYTHON RUNTIME DETECTOR
// -------------------------------------------------------------

function findPythonBinary() {
  const isWin = os.platform() === "win32";
  const candidates = isWin ? ["python", "py", "python3"] : ["python3", "python"];

  for (const cmd of candidates) {
    const check = spawnSync(cmd, ["-c", "import sys; print(sys.executable)"], {
      encoding: "utf-8",
    });
    if (check.status === 0 && check.stdout.trim()) {
      return { cmd, execPath: check.stdout.trim() };
    }
  }
  throw new Error("Could not find a valid Python 3 installation on PATH.");
}

// -------------------------------------------------------------
// 3. AOT BYTECODE COMPILER
// -------------------------------------------------------------

function compileToBytecode(pythonCmd, sourceCode, sourcePath) {
  const pyWorker = `
import marshal, sys
src = sys.stdin.read()
try:
    code = compile(src, ${JSON.stringify(sourcePath)}, 'exec')
    dump = marshal.dumps(code)
    sys.stdout.write(','.join(str(b) for b in dump))
except Exception as e:
    sys.stderr.write(str(e))
    sys.exit(1)
`;

  const child = spawnSync(pythonCmd, ["-c", pyWorker], {
    input: sourceCode,
    encoding: "utf-8",
    maxBuffer: 64 * 1024 * 1024,
  });

  if (child.status !== 0) {
    throw new Error(child.stderr.trim() || "Bytecode compilation failed.");
  }

  const raw = child.stdout.trim();
  if (!raw) return [];
  return raw.split(",").map((n) => Number.parseInt(n, 10));
}

// -------------------------------------------------------------
// 4. HARDENED NATIVE C RUNTIME GENERATOR
// -------------------------------------------------------------

function formatHexDump(bytes) {
  const lines = [];
  const chunkSize = 16;
  for (let i = 0; i < bytes.length; i += chunkSize) {
    const chunk = bytes.slice(i, i + chunkSize);
    const hex = chunk.map((b) => "0x" + b.toString(16).padStart(2, "0")).join(", ");
    lines.push(`    ${hex},`);
  }
  return lines.join("\n");
}

function generateNativeC(bytes, sourcePath, sysPythonPath) {
  return `/* Generated by Bun Native Python AOT Compiler */
#define PY_SSIZE_T_CLEAN
#include <Python.h>
#include <marshal.h>
#include <wchar.h>

static const unsigned char aot_bytecode[] = {
${formatHexDump(bytes)}
};
static const size_t aot_bytecode_len = ${bytes.length};

int main(int argc, char *argv[]) {
    PyStatus status;
    PyConfig config;
    PyConfig_InitPythonConfig(&config);

    /* 1. Prevent Python from intercepting binary arguments */
    config.parse_argv = 0;

    /* 2. Anchor program_name to system python so standard libraries are discovered */
    status = PyConfig_SetBytesString(&config, &config.program_name, ${JSON.stringify(sysPythonPath)});
    if (PyStatus_Exception(status)) { PyConfig_Clear(&config); return 1; }

    /* 3. Forward exact command-line arguments to sys.argv */
    status = PyConfig_SetBytesArgv(&config, argc, argv);
    if (PyStatus_Exception(status)) { PyConfig_Clear(&config); return 1; }

    /* 4. Boot CPython Runtime Engine */
    status = Py_InitializeFromConfig(&config);
    PyConfig_Clear(&config);
    if (PyStatus_Exception(status)) { return 1; }

    /* 5. Inject application directory into sys.path */
    PyRun_SimpleString("import sys, os\\n"
                       "if '' not in sys.path:\\n"
                       "    sys.path.insert(0, os.path.abspath('.'))\\n");

    /* 6. Populate __main__ context */
    PyObject *main_mod = PyImport_AddModule("__main__");
    PyObject *global_dict = PyModule_GetDict(main_mod);
    PyDict_SetItemString(global_dict, "__file__", PyUnicode_FromString(${JSON.stringify(sourcePath)}));
    PyDict_SetItemString(global_dict, "__name__", PyUnicode_FromString("__main__"));

    /* 7. Unmarshal and execute AOT bytecode */
    PyObject *code_obj = PyMarshal_ReadObjectFromString((const char *)aot_bytecode, aot_bytecode_len);
    if (!code_obj) {
        PyErr_Print();
        Py_Finalize();
        return 1;
    }

    PyObject *result = PyEval_EvalCode(code_obj, global_dict, global_dict);
    int exit_code = 0;

    if (!result) {
        if (PyErr_ExceptionMatches(PyExc_SystemExit)) {
            PyObject *exc, *val, *tb;
            PyErr_Fetch(&exc, &val, &tb);
            if (val && PyLong_Check(val)) {
                exit_code = (int)PyLong_AsLong(val);
            }
        } else {
            PyErr_Print();
            exit_code = 1;
        }
    } else {
        Py_DECREF(result);
    }

    Py_DECREF(code_obj);
    Py_Finalize();
    return exit_code;
}
`;
}

// -------------------------------------------------------------
// 5. CROSS-PLATFORM COMPILER & LINKER RESOLVER
// -------------------------------------------------------------

function getBuildFlags(pythonCmd) {
  // Uses Python's internal sysconfig module (works on Linux, macOS, and Windows)
  const probe = `
import sysconfig, sys, os, json

includes = [
    sysconfig.get_path('include'),
    sysconfig.get_path('platinclude')
]
includes = list(dict.fromkeys([p for p in includes if p and os.path.isdir(p)]))

libdir = sysconfig.get_config_var('LIBDIR') or os.path.join(sys.base_prefix, 'libs')
ldversion = sysconfig.get_config_var('LDVERSION') or f"{sys.version_info.major}.{sys.version_info.minor}"
pyver_nodot = f"{sys.version_info.major}{sys.version_info.minor}"

cflags = [f"-I{p}" for p in includes]
ldflags = []

if sys.platform != "win32":
    if libdir and os.path.isdir(libdir):
        ldflags.append(f"-L{libdir}")
    ldflags.append(f"-lpython{ldversion}")
    # Link math/pthread on POSIX if present
    ldflags.extend(["-lm", "-lpthread"])
else:
    # Windows Linker configuration
    if os.path.isdir(libdir):
        ldflags.append(f"-L{libdir}")
    ldflags.append(f"-lpython{pyver_nodot}")

print(json.dumps({'cflags': cflags, 'ldflags': ldflags}))
`;

  const child = spawnSync(pythonCmd, ["-c", probe], { encoding: "utf-8" });
  if (child.status !== 0) {
    throw new Error("Failed to resolve Python sysconfig: " + child.stderr);
  }
  return JSON.parse(child.stdout.trim());
}

function detectHostCompiler() {
  const isWin = os.platform() === "win32";
  const compilers = isWin ? ["gcc", "clang", "cl"] : ["gcc", "clang", "cc"];

  for (const c of compilers) {
    const test = spawnSync(c, ["--version"]);
    if (test.status === 0) return c;
  }
  throw new Error("No C compiler found (checked: " + compilers.join(", ") + ").");
}

// -------------------------------------------------------------
// 6. CLI PARSER (FROM SCRATCH)
// -------------------------------------------------------------

function parseCliArgs() {
  const argv = process.argv.slice(2);
  const isWin = os.platform() === "win32";
  const options = {
    input: null,
    output: isWin ? "a.exe" : "a.out",
    keepC: false,
    verbose: false,
  };

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "-o") {
      options.output = argv[++i];
    } else if (arg === "--keep-c") {
      options.keepC = true;
    } else if (arg === "-v" || arg === "--verbose") {
      options.verbose = true;
    } else if (arg === "-h" || arg === "--help") {
      console.log("Usage: bun pyle.js <source.py> [-o <binary>] [--keep-c] [-v]");
      process.exit(0);
    } else if (!arg.startsWith("-") && !options.input) {
      options.input = arg;
    } else {
      console.error(`Unknown or duplicate argument: ${arg}`);
      process.exit(1);
    }
  }

  if (!options.input) {
    console.error("Error: No input file provided.");
    console.log("Usage: bun pyle.js <source.py> [-o <binary>] [--keep-c] [-v]");
    process.exit(1);
  }

  return options;
}

// -------------------------------------------------------------
// 7. DRIVER / PIPELINE
// -------------------------------------------------------------

function main() {
  const opts = parseCliArgs();
  const srcFile = path.resolve(opts.input);
  const outFile = path.resolve(opts.output);
  const cFile = outFile + ".c";

  if (!fs.existsSync(srcFile)) {
    console.error(`Error: File not found: ${srcFile}`);
    process.exit(1);
  }

  console.log("==========================================================");
  console.log("    BUN NATIVE PYTHON AOT COMPILER (PyCompile)           ");
  console.log("==========================================================");

  // 1. Detect Python
  const { cmd: pyCmd, execPath: sysPyPath } = findPythonBinary();
  if (opts.verbose) {
    console.log(`[Host] Python: ${sysPyPath} (${pyCmd})`);
    console.log(`[Host] Platform: ${os.platform()} (${os.arch()})`);
  }

  // 2. Scan Imports
  console.log(`[1/4] Reading source: ${opts.input}`);
  const srcContent = fs.readFileSync(srcFile, "utf-8");
  const imports = extractImports(srcContent);

  console.log(`[2/4] Scanned ${imports.length} top-level module import(s):`);
  for (const imp of imports) {
    if (imp.type === "ModImport") {
      console.log(`      -> import ${imp.module}`);
    } else {
      console.log(`      -> from ${imp.module} import ${imp.target}`);
    }
  }

  // 3. Compile Bytecode
  console.log("[3/4] Compiling AST into Bytecode...");
  let bytecode;
  try {
    bytecode = compileToBytecode(pyCmd, srcContent, srcFile);
  } catch (err) {
    console.error("\n--- [PYTHON COMPILATION ERROR] ---");
    console.error(err.message);
    process.exit(1);
  }
  console.log(`      Compiled Bytecode Size: ${bytecode.length} bytes.`);

  // 4. Generate C Glue Code
  const cCode = generateNativeC(bytecode, srcFile, sysPyPath);
  fs.writeFileSync(cFile, cCode, "utf-8");

  // 5. Invoke Host Linker
  console.log(`[4/4] Invoking C Compiler: ${path.basename(outFile)}`);
  const compiler = detectHostCompiler();
  const { cflags, ldflags } = getBuildFlags(pyCmd);

  const compileArgs = [
    "-O2",
    cFile,
    ...cflags,
    ...ldflags,
    "-o",
    outFile,
  ];

  if (opts.verbose) {
    console.log(`Exec: ${compiler} ${compileArgs.join(" ")}`);
  }

  const linkResult = spawnSync(compiler, compileArgs, {
    stdio: opts.verbose ? "inherit" : "pipe",
    encoding: "utf-8",
  });

  if (linkResult.status !== 0) {
    console.error("\n--- [C LINKER ERROR] ---");
    if (!opts.verbose && linkResult.stderr) {
      console.error(linkResult.stderr);
    }
    process.exit(1);
  }

  // Cleanup temporary C file if not specified
  if (!opts.keepC) {
    try {
      fs.unlinkSync(cFile);
    } catch (_) {}
  }

  console.log("==========================================================");
  console.log(`SUCCESS: Native Executable Compiled -> ${outFile}`);
  console.log("==========================================================");
}

main();
